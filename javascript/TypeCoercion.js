// Implicit Coercion examples
"5" + 2   // "52" (The number 2 is coerced into a string for concatenation)
"5" - 2   // 3    (The string "5" is coerced into a number for subtraction)
5 + true  // 6    (The boolean true is coerced into the number 1)
5 + false // 5    (The boolean false is coerced into the number 0)
